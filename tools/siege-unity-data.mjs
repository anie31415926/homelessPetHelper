import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOG, TEXT } from '../src/siege/catalog.js';
import { CONTENT, CONTENT_TEXT, UNIT_DEFAULTS } from './siege-content.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const base = 'unity/HomelessPetHelper/Assets';
const pascal = key => key[0].toUpperCase() + key.slice(1);
const groups = { Rules: CATALOG.rules, Unit: {...CATALOG.units[0], ...UNIT_DEFAULTS, mergeCount: 0, abilityPower: 0, abilityCharges: 0, abilityCooldownMs: 0}, Tower: CATALOG.tower,
    Profile: CATALOG.animalStates[0], Pad: CATALOG.map.pads[0],
    TowerType: CONTENT.towers[0], Encounter: {...CONTENT.encounters[0], rotateSupply: false, manualMergeOnly: false} };
const type = (key, value) => key === 'upgradeId' || value === null ? 'string' :
    Array.isArray(value) ? 'string[]' :
    typeof value === 'boolean' ? 'bool' : typeof value === 'string' ? 'string' :
        ['cost','stepMs','durationMs','playerPeriodMs','handSize','bagCopies','openingEnergy','energyCap',
            'resourcePeriodMs','defenderResourcePeriodMs','defenderEnergyCap','defenderOpeningEnergy','defenderBuildCost',
            'fastBuildDurationMs','maxTroops','defenseGridSize','turnEnergy','turnDraw','mergeCost','maxLog','guardDurationMs','slapPeriodMs','sweepRecoveryMs',
            'animalRepairs','repairDurationMs','repairCooldownMs','buildDurationMs','buildOnAnimalTurn',
            'animalBuilds','rerouteDurationMs','attackMs','abilityPeriodMs','periodMs',
            'mergeCount','abilityCharges','abilityCooldownMs','burstHits','burstIntervalMs','auraTargets','auraRearmMs','warningMs','zoneDurationMs','sweepDelayMs',
            'holdDurationMs','holdRecoveryMs','holdCooldownMs','holdProtectionMs',
            'carryDelayMs','carryDurationMs','carryRecoveryMs','carryCooldownMs','carryProtectionMs'].includes(key) ? 'int' : 'double';
let source = '// <auto-generated />\n// Sources: src/siege/definitions.json, content.json; node tools/siege-unity-data.mjs\n' +
    'using System;\n\nnamespace HomelessPetHelper.Modules.Siege\n{\n';
source += '    [Serializable]\n    public sealed class SiegeCatalogData\n    {\n' +
    '        public int schemaVersion;\n        public RulesDto rules;\n        public UnitDto[] units;\n' +
    '        public TowerDto tower;\n        public ProfileDto[] animalStates;\n        public MapDto map;\n' +
    '        public UnitDto[] contentUnits;\n        public TowerTypeDto[] towerTypes;\n        public EncounterDto[] encounters;\n';
for (const [name, example] of Object.entries(groups)) {
    source += `\n        [Serializable]\n        public sealed class ${name}Dto\n        {\n`;
    for (const [key, value] of Object.entries(example)) source += `            public ${type(key, value)} ${key};\n`;
    source += '        }\n';
}
source += `
        [Serializable]
        public sealed class MapDto
        {
            public double width, height;
            public LaneDto[] lanes;
            public PadDto[] pads;
        }
        [Serializable]
        public sealed class LaneDto
        {
            public string id, nameKey;
            public bool open;
            public PointDto[] points;
        }
        [Serializable]
        public sealed class PointDto { public double x, y; }
    }
`;
for (const [name, example] of Object.entries(groups)) {
    source += `\n    public sealed class Siege${name}Definition\n    {\n`;
    for (const [key, value] of Object.entries(example)) source += `        public ${Array.isArray(value) ? 'System.Collections.Generic.IReadOnlyList<string>' : type(key, value)} ${pascal(key)} { get; }\n`;
    source += `\n        internal Siege${name}Definition(SiegeCatalogData.${name}Dto data)\n        {\n`;
    for (const [key, value] of Object.entries(example)) source += `            ${pascal(key)} = ${Array.isArray(value) ? `Array.AsReadOnly((string[])data.${key}.Clone())` : `data.${key}`};\n`;
    source += '        }\n    }\n';
}
source += '}\n';
const data = structuredClone(CATALOG);
data.contentUnits = CONTENT.units.map(u => ({...UNIT_DEFAULTS, ...u}));
data.towerTypes = structuredClone(CONTENT.towers);
data.encounters = structuredClone(CONTENT.encounters);
delete data.map.animalImage;
data.map.lanes.forEach(lane => { lane.points = lane.points.map(([x,y]) => ({x,y})); });
const extra = JSON.parse(fs.readFileSync(path.join(root, 'src/siege/unity-text.zh-CN.json'), 'utf8'));
const trial = JSON.parse(fs.readFileSync(path.join(root, 'src/siege/loadout-trial.json'), 'utf8'));
const trialUnits = trial.units.map(unit => {
    const baseUnit = data.contentUnits.find(item => item.id === unit.baseId);
    if (!baseUnit) throw new Error(`Unknown trial base unit: ${unit.baseId}`);
    const {baseId, ...changes} = unit;
    return {...baseUnit, ...changes};
});
const trialEncounters = trial.loadouts.map(loadout => {
    const encounter = data.encounters.find(item => item.id === loadout.encounterId);
    if (!encounter) throw new Error(`Unknown trial encounter: ${loadout.encounterId}`);
    return {...encounter, id: loadout.id, unitIds: loadout.unitIds, rotateSupply: true, manualMergeOnly: trial.manualMergeOnly};
});
const trialText = {...TEXT, ...extra, ...CONTENT_TEXT, ...trial.text};
const outputs = {
    [`${base}/Scripts/Modules/Siege/SiegeCatalogData.cs`]: source,
    [`${base}/Settings/Siege/SiegeLoadoutTrial.json`]: JSON.stringify({
        catalog: {...data, contentUnits: [...data.contentUnits, ...trialUnits], encounters: trialEncounters},
        text: {entries: Object.entries(trialText).map(([key,value]) => ({key,value}))}
    }, null, 2) + '\n',
    [`${base}/Settings/Siege/SiegeTrialData.json`]: JSON.stringify(data, null, 2) + '\n',
    [`${base}/Settings/Siege/SiegeTrialText.json`]: JSON.stringify({entries: Object.entries({...TEXT,...extra,...CONTENT_TEXT}).map(([key,value]) => ({key,value}))}, null, 2) + '\n'
};
for (const [relative, content] of Object.entries(outputs)) {
    const file = path.join(root, relative);
    if (process.argv.includes('--check')) {
        if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== content) throw new Error(`Stale generated siege data: ${relative}`);
    } else {
        fs.mkdirSync(path.dirname(file), {recursive:true});
        fs.writeFileSync(file, content, 'utf8');
    }
}
console.log(`Unity siege data ${process.argv.includes('--check') ? 'verified' : 'generated'}: ${Object.keys(outputs).length} files.`);
